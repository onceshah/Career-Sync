"""
AIDecisionPipeline: Deliverable D1 Enterprise AI Decision Pipeline orchestrator.

Layer: Application Layer
Role: Orchestrates prompt construction, LLM provider invocation, response parsing,
      and policy constraint enforcement across the AI decision pipeline.

Interacting Components:
    - app.domain.models (StructuredEmail, PolicyDecision)
    - app.ai.models (AIDecision)
    - app.ai.prompt_builder (PromptBuilder)
    - app.ai.parser (AIResponseParser)
    - app.ai.factory (LLMProviderFactory)
"""

import logging
from typing import Optional

from app.ai.factory import LLMProviderFactory
from app.ai.interfaces import LLMProvider
from app.ai.models import AIDecision
from app.ai.parser import AIResponseParser
from app.ai.prompt_builder import PromptBuilder
from app.domain.models import PolicyDecision, StructuredEmail

logger = logging.getLogger(__name__)


class AIDecisionPipeline:
    """
    Orchestrates prompt construction, LLM inference, response parsing, and policy enforcement.

    Responsibility:
        Coordinates the execution of the AI decision pipeline while strictly preserving
        domain Enum types and enforcing deterministic policy locks when overrides are disabled.

    Inputs:
        provider (Optional[LLMProvider]): Provider implementation for LLM generation.

    Outputs:
        AIDecisionPipeline instance.

    Role within Architecture:
        Application Layer orchestrator for AI triage workflow.
    """

    def __init__(self, provider: Optional[LLMProvider] = None):
        """
        Initializes the AIDecisionPipeline with an optional LLMProvider.

        Args:
            provider: Custom LLMProvider or None (defaults to factory instance).
        """
        self.provider = provider or LLMProviderFactory.create()

    def process(
        self,
        email: StructuredEmail,
        policy_decision: PolicyDecision,
    ) -> AIDecision:
        """
        Execute the Enterprise AI Decision Pipeline.

        Args:
            email: StructuredEmail domain object.
            policy_decision: Deterministic PolicyDecision domain object.

        Returns:
            Validated AIDecision domain model containing strongly-typed Enum instances.

        Side Effects:
            Sends HTTP/API request to external LLM provider and logs progress.
        """

        msg_id = (
            email.headers.message_id
            if email.headers and email.headers.message_id
            else "msg-unknown"
        )

        logger.info(
            "Executing AI Decision Pipeline for email '%s'.",
            msg_id,
        )

        prompt = PromptBuilder.build_prompt(
            email=email,
            policy_decision=policy_decision,
        )

        raw_completion = self.provider.generate(prompt)

        ai_decision = AIResponseParser.parse(
            raw_response=raw_completion,
            expected_email_id=msg_id,
        )

        ai_decision = self._enforce_policy_constraints(
            ai_decision,
            policy_decision,
        )

        logger.info(
            "AI Decision generated | Folder=%s | Priority=%s | Confidence=%.2f",
            ai_decision.recommended_folder.value,
            ai_decision.priority.value,
            ai_decision.confidence,
        )

        return ai_decision

    @staticmethod
    def _enforce_policy_constraints(
        ai_decision: AIDecision,
        policy_decision: PolicyDecision,
    ) -> AIDecision:
        """
        Prevent AI from overriding deterministic policy decisions when overrides are disabled.

        Args:
            ai_decision: Proposed AIDecision generated by LLM parser.
            policy_decision: Deterministic PolicyDecision from D0 policy engine.

        Returns:
            Policy-enforced AIDecision instance.
        """

        override_allowed = getattr(
            policy_decision,
            "is_override_allowed",
            getattr(policy_decision, "override_allowed", True)
        )

        if override_allowed:
            return ai_decision

        updates = {}

        if (
            policy_decision.folder
            and ai_decision.recommended_folder != policy_decision.folder
        ):
            logger.warning(
                "Policy override blocked. Restoring folder '%s'.",
                policy_decision.folder.value,
            )
            updates["recommended_folder"] = policy_decision.folder

        if (
            policy_decision.priority
            and ai_decision.priority != policy_decision.priority
        ):
            logger.warning(
                "Policy override blocked. Restoring priority '%s'.",
                policy_decision.priority.value,
            )
            updates["priority"] = policy_decision.priority

        if not updates:
            return ai_decision

        updates["policy_overridden"] = False

        if policy_decision.audit:
            matched = ", ".join(policy_decision.audit.matched_rules)
            updates["reasoning"] = (
                f"{ai_decision.reasoning}\n"
                f"[D0 Policy Lock Applied: {matched}]"
            )

        return ai_decision.model_copy(update=updates)
