"""
AI Decision models for the Enterprise AI Decision Pipeline.

Layer: Domain / AI Pipeline Layer
Role: Defines prompt structures, action recommendations, and final validated
      AIDecision output models produced by the AI Decision Pipeline.

Interacting Components:
    - app.domain.enums (FolderType, CategoryType, PriorityLevel, VendorType, ActionType)
    - app.ai.prompt_builder (Consumes Prompt)
    - app.ai.parser (Produces AIDecision)
    - app.ai.pipeline (Orchestrates AIDecision production)
"""

from typing import List, Optional

from pydantic import BaseModel, Field

from app.domain.enums import (
    ActionType,
    CategoryType,
    FolderType,
    PriorityLevel,
    VendorType,
)


class Prompt(BaseModel):
    """
    Provider-agnostic prompt package for LLM generation.

    Responsibility:
        Encapsulates system and user prompt strings.

    Inputs:
        system_prompt (str): System instruction prompt.
        user_prompt (str): User context prompt.

    Outputs:
        Prompt object.

    Role within Architecture:
        Data package passed from PromptBuilder to LLMProvider implementations.
    """

    system_prompt: str
    user_prompt: str


class ActionRecommendation(BaseModel):
    """
    Recommended operational action generated by the AI engine.

    Responsibility:
        Encapsulates an action type enum and descriptive metadata.

    Inputs:
        action_type (ActionType): Typed action enum.
        description (str): Human-readable explanation.
        target (Optional[str]): Operational target identifier.

    Outputs:
        ActionRecommendation object.

    Role within Architecture:
        Component model inside AIDecision.
    """

    action_type: ActionType = Field(
        ...,
        description="Type of action recommended.",
    )

    description: str = Field(
        ...,
        description="Human-readable explanation of the recommended action.",
    )

    target: Optional[str] = Field(
        default=None,
        description="Optional queue, folder, user, label, or destination.",
    )


class AIDecision(BaseModel):
    """
    Final validated decision output produced by the AI Decision Pipeline.

    Responsibility:
        Contains strongly-typed enum decisions (recommended_folder, categories,
        priority, vendor) and supporting reasoning from LLM evaluation.

    Inputs:
        email_id, recommended_folder (FolderType), categories (List[CategoryType]),
        priority (PriorityLevel), vendor (Optional[VendorType]), project, reasoning,
        confidence, recommended_actions, policy_overridden.

    Outputs:
        AIDecision domain model instance.

    Role within Architecture:
        Core output contract of the Deliverable D1 AI Decision Pipeline.
    """

    email_id: str = Field(
        ...,
        description="Unique identifier of the processed email.",
    )

    recommended_folder: FolderType = Field(
        ...,
        description="Recommended destination folder.",
    )

    categories: List[CategoryType] = Field(
        default_factory=list,
        description="Detected business categories.",
    )

    priority: PriorityLevel = Field(
        ...,
        description="Assigned processing priority.",
    )

    vendor: Optional[VendorType] = Field(
        default=None,
        description="Detected vendor if applicable.",
    )

    project: Optional[str] = Field(
        default=None,
        description="Detected project identifier.",
    )

    reasoning: str = Field(
        ...,
        description="Explanation supporting the AI decision.",
    )

    confidence: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Confidence score between 0.0 and 1.0.",
    )

    recommended_actions: List[ActionRecommendation] = Field(
        default_factory=list,
        description="Recommended operational actions.",
    )

    policy_overridden: bool = Field(
        default=False,
        description="True if the AI recommends overriding the deterministic policy decision.",
    )
