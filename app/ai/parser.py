"""
AI Response Parser for the Enterprise AI Decision Pipeline.

Layer: Boundary / Parsing Layer (AI → Domain)
Role: Deserializes and validates raw LLM JSON completion text into a strongly-typed
      AIDecision domain model with proper Enum objects.

Interacting Components:
    - app.domain.enums (FolderType, CategoryType, PriorityLevel, VendorType, ActionType)
    - app.ai.models (AIDecision, ActionRecommendation)
    - app.ai.pipeline (Invokes AIResponseParser during pipeline execution)
"""

import json
import re
import logging
from typing import Any, Dict

from app.domain.enums import FolderType, CategoryType, PriorityLevel, VendorType, ActionType
from app.ai.models import AIDecision, ActionRecommendation

logger = logging.getLogger(__name__)


class AIResponseParser:
    """
    Parses and validates raw JSON responses into strongly-typed AIDecision Pydantic models.

    Responsibility:
        Deserializes string tokens from raw LLM output into validated Enum values and domain fields.

    Inputs:
        raw_response (str): Raw text generated by LLM provider.
        expected_email_id (str): Email identifier fallback.

    Outputs:
        AIDecision: Strongly-typed AI decision model.

    Role within Architecture:
        Boundary parser converting external LLM JSON text to internal domain enums.
    """

    @classmethod
    def parse(cls, raw_response: str, expected_email_id: str) -> AIDecision:
        """
        Parses raw LLM completion string into a validated AIDecision object.

        Args:
            raw_response: Raw text payload returned by LLM.
            expected_email_id: Fallback message identifier if missing in JSON.

        Returns:
            Validated AIDecision domain object containing Enum instances.

        Raises:
            ValueError: If raw_response cannot be parsed as a JSON dictionary.
        """
        cleaned_json_text = cls._strip_json_fences(raw_response)

        try:
            data = json.loads(cleaned_json_text)
        except Exception as exc:
            raise ValueError(f"Failed to parse LLM response as JSON: {str(exc)}\nRaw output:\n{raw_response}") from exc

        if not isinstance(data, dict):
            raise ValueError("Parsed LLM output is not a JSON object.")

        email_id = data.get("email_id") or expected_email_id

        # Validate Folder
        folder_str = str(data.get("recommended_folder", "INBOX")).upper()
        try:
            recommended_folder = FolderType(folder_str)
        except ValueError:
            recommended_folder = FolderType.INBOX

        # Validate Categories
        raw_cats = data.get("categories", [])
        categories = []
        if isinstance(raw_cats, list):
            for cat_item in raw_cats:
                try:
                    categories.append(CategoryType(str(cat_item).upper()))
                except ValueError:
                    pass
        if not categories:
            categories = [CategoryType.OTHER]

        # Validate Priority
        prio_str = str(data.get("priority", "NORMAL")).upper()
        try:
            priority = PriorityLevel(prio_str)
        except ValueError:
            priority = PriorityLevel.NORMAL

        # Validate Vendor
        vendor_val = data.get("vendor")
        vendor = None
        if vendor_val:
            try:
                vendor = VendorType(str(vendor_val).upper())
            except ValueError:
                vendor = VendorType.UNKNOWN

        project = data.get("project")
        reasoning = str(data.get("reasoning", "AI Triage analysis completed."))

        raw_conf = data.get("confidence", 0.85)
        try:
            confidence = float(raw_conf)
            confidence = max(0.0, min(1.0, confidence))
        except (ValueError, TypeError):
            confidence = 0.85

        raw_actions = data.get("recommended_actions", [])
        recommended_actions = []
        if isinstance(raw_actions, list):
            for act in raw_actions:
                if isinstance(act, dict) and "action_type" in act and "description" in act:
                    try:
                        act_type = ActionType(str(act["action_type"]).upper())
                        recommended_actions.append(
                            ActionRecommendation(
                                action_type=act_type,
                                description=str(act["description"]),
                                target=act.get("target")
                            )
                        )
                    except ValueError:
                        pass

        policy_overridden = bool(data.get("policy_overridden", False))

        return AIDecision(
            email_id=email_id,
            recommended_folder=recommended_folder,
            categories=categories,
            priority=priority,
            vendor=vendor,
            project=project,
            reasoning=reasoning,
            confidence=confidence,
            recommended_actions=recommended_actions,
            policy_overridden=policy_overridden
        )

    @staticmethod
    def _strip_json_fences(text: str) -> str:
        """
        Strips ```json ... ``` markdown code block wrappers from response text.

        Args:
            text: Raw input string possibly containing markdown block formatting.

        Returns:
            Cleaned JSON string content.
        """
        text = text.strip()
        match = re.search(r"```(?:json)?\s*([\s\S]*?)\s*```", text, re.IGNORECASE)
        if match:
            return match.group(1).strip()
        return text

