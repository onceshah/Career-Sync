"""
Interfaces for Enterprise AI providers.
"""

from __future__ import annotations

from abc import ABC, abstractmethod

from app.ai.models import Prompt


class LLMProvider(ABC):
    """
    Abstract interface for all LLM providers.

    Every provider must accept a provider-agnostic Prompt
    and return the raw completion generated by the model.
    """

    @abstractmethod
    def generate(self, prompt: Prompt) -> str:
        """
        Generate a completion from the supplied prompt.

        Parameters
        ----------
        prompt : Prompt
            Provider-independent prompt package.

        Returns
        -------
        str
            Raw completion returned by the underlying LLM.
        """
        raise NotImplementedError